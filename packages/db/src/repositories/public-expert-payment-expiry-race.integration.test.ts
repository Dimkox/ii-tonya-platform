async function clock(expired = false) {
  await db.db.execute(
    sql.raw(
      `create or replace function early_bird_current_time() returns timestamptz language sql volatile as $$ select '${expired ? "2027-01-11T15:00:00Z" : at}'::timestamptz $$`,
    ),
  );
}
async function call(
  name: string,
  args: unknown[],
  c: Pick<PoolClient, "query"> = db.db.$client,
) {
  return (
    await c.query(
      `select early_bird_private.${name}(${args.map((_, i) => `$${i + 1}`).join(",")}) value`,
      args,
    )
  ).rows[0]!.value;
}
