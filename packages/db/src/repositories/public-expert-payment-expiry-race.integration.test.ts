// Credit is generated by the existing referral+canonical settlement engine, not raw ledger inserts.
async function earnCredit(f: Owner) {
  await db.db.execute(
    sql`update experts set active=true,verified=true where id=${f.expertId}::uuid`,
  );
  await db.seedFirstSettlement(f.expertId);
  await db.db.execute(
    sql`update expert_referral_feature_controls set version=version+1,reward_grants_enabled=true where control_key='expert_referrals'`,
  );
  const invitee = await db.createExpertIdentity();
  const crypto = new ExpertCodeCrypto({
    currentVersion: "v1",
    activeVersions: ["v1"],
    key: () => new Uint8Array(32).fill(37),
  });
  const repo = new PostgresExpertReferralRepository(db.db, crypto);
  const audit = await db.createAdminAudit({
    action: "expert_referral.batch_generate",
    objectId: f.expertId,
  });
  const batch = await repo.issueBatch({
    inviterExpertId: f.expertId,
    count: 1,
    issuedByAdminId: audit.adminId,
    approvalId: audit.approvalId,
    adminSessionIdHash: audit.sessionIdHash,
  });
  await repo.redeemCode({
    plaintext: batch.codes[0]!.plaintext,
    userId: invitee.userId,
    provider: invitee.provider,
    externalId: invitee.externalId,
  });
  const tariff = await db.createResidencyTariff({
    tariffKey: `boundary-${randomUUID()}`,
    displayName: "Legacy",
    priceMinor: 999000,
    durationSeconds: 2592000,
    commercialPolicyVersion: "legacy_residency_v1",
  });
  const order = await new PostgresExpertResidencyRepository(
    db.db,
  ).createCheckoutOrder({
    expertId: invitee.expertId,
    tariffVersionId: tariff,
    providerDeadline: new Date(Date.now() + 3600000),
    idempotencyKey: randomUUID(),
  });
  const now = new Date().toISOString();
  const proof = verifiedEventFixture(
    {
      kind: "settled",
      provider: "boundary-fixture",
      eventId: randomUUID(),
      paymentId: `reward_${randomUUID()}`,
      orderId: order.id,
      amountMinor: order.cashMinor,
      currency: "RUB",
      occurredAt: now,
      payloadDigest: hash(order.id),
    },
    {
      verificationId: randomUUID(),
      verifierKeyVersion: "boundary-fixture-v1",
      verifiedAt: now,
    },
  );
  expect(
    (
      await new PostgresExpertResidencyProviderInboxRepository(db.db).settle(
        proof,
      )
    ).rewardGranted,
  ).toBe(true);
}
async function checkout(f: Owner) {
  await clock();
  const quote = await f.financial.quoteMain({
    ...correctionEvent(f.workScope),
    tariffVersionId: f.tariffId,
    termMonths: 1,
    revision: f.revision,
  });
  await f.financial.acceptMain({
    ...correctionEvent(f.workScope),
    quoteId: quote.id,
    revision: f.revision,
  });
  const vault = createPayerReceiptVault({
    activeKeyId: "fixture",
    keys: new Map([["fixture", new Uint8Array(32).fill(13)]]),
  });
  await new PostgresPayerReceiptContactRepository(db.db, vault, 30).capture({
    userId: f.userId,
    quoteId: quote.id,
    email: "synthetic@example.com",
    idempotencyKey: randomUUID(),
  });
  const contactId = (
    await db.db.$client.query(
      "select id from payer_receipt_contacts where quote_id=$1 and user_id=$2",
      [quote.id, f.userId],
    )
  ).rows[0]!.id as string;
  const order = await f.financial.createMainInvoice({
    ...correctionEvent(f.workScope),
    revision: f.revision,
  });
  await db.db.execute(
    sql`insert into payer_receipt_order_bindings(order_id,contact_id,quote_id,user_id) values(${order.orderId}::uuid,${contactId}::uuid,${quote.id}::uuid,${f.userId}::uuid)`,
  );
  // Only fixture timestamps move through the established PostgreSQL clock seam.
  await db.db.transaction(async (tx) => {
    await tx.execute(
      sql`alter table expert_residency_orders disable trigger expert_campaign_order_snapshot_immutable`,
    );
    await tx.execute(
      sql`update expert_residency_orders set payment_deadline='2027-01-11T14:00:00Z',provider_deadline='2027-01-11T14:00:00Z' where id=${order.orderId}::uuid`,
    );
    await tx.execute(
      sql`alter table expert_residency_orders enable trigger expert_campaign_order_snapshot_immutable`,
    );
    await tx.execute(
      sql`alter table payer_receipt_contacts disable trigger payer_receipt_contact_guard`,
    );
    await tx.execute(
      sql`update payer_receipt_contacts set captured_at='2027-01-11T11:00:00Z',expires_at='2027-01-11T14:00:00Z' where id=${contactId}::uuid`,
    );
    await tx.execute(
      sql`alter table payer_receipt_contacts enable trigger payer_receipt_contact_guard`,
    );
  });
  const descriptor = {
    requestId: randomUUID(),
    idempotencyKey: randomUUID(),
    legacyDeliveryOperationId: randomUUID(),
    kind: "main_create",
    requestDigest: hash(randomUUID()),
    bodyVersion: 1,
    ciphertext: "synthetic-sealed-boundary",
    keyReference: "fixture:key",
    bodyExpiresAt: "2027-01-11T13:00:00.000Z",
  };
  const snapshot = await call("public_main_prepare", [
    f.userId,
    order.orderId,
    contactId,
    JSON.stringify(descriptor),
  ]);
  expect(snapshot).toMatchObject({ state: "prepared" });
  return { ...f, order, contactId, descriptor, snapshot };
}
type Checkout = Awaited<ReturnType<typeof checkout>>;
async function lock(c: PoolClient, f: Checkout) {
  await c.query("select pg_advisory_xact_lock(hashtextextended($1,0))", [
    f.userId,
  ]);
  await c.query(
    "select id from expert_residency_orders where id=$1 for update",
    [f.order.orderId],
  );
}
async function canonicalExpire(f: Checkout, abort = false) {
  return db.db
    .transaction(async (tx) => {
      await tx.execute(
        sql`select pg_advisory_xact_lock(hashtextextended(${f.userId},0))`,
      );
      await tx.execute(
        sql`select id from expert_residency_orders where id=${f.order.orderId}::uuid for update`,
      );
      const expired = await expireLockedExpertResidencyOrder(
        tx,
        { id: f.order.orderId, expertId: f.expertId },
        sql`early_bird_current_time()`,
      );
      if (abort) throw Error("fixture_abort_after_canonical_expiry");
      return expired;
    })
    .catch((error: unknown) => {
      if (error instanceof Error && error.cause instanceof Error)
        throw error.cause;
      throw error;
    });
}
async function state(f: Checkout) {
  return (
    await db.db.$client.query(
      `select r.state,o.status,
 (select coalesce(sum(amount_minor),0)::text from expert_referral_ledger_entries where order_id=o.id and entry_kind in('reservation','release')) reserved,
 (select count(*)::int from expert_referral_ledger_entries where order_id=o.id and entry_kind='release') releases,
 (select count(*)::int from public_expert_payment_observations where request_id=r.id) observations
 from public_expert_payment_requests r join expert_residency_orders o on o.id=r.order_id where r.id=$1`,
      [f.descriptor.requestId],
    )
  ).rows[0]!;
}
