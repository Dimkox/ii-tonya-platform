async function bind(
  f: Checkout,
  status: "pending" | "succeeded" = "succeeded",
) {
  const providerId = `boundary_${randomUUID()}`;
  const fact = {
    version: 1,
    requestId: f.descriptor.requestId,
    providerObjectId: providerId,
    parentPaymentId: null,
    status,
    paid: status === "succeeded",
    amountMinor: f.order.cashMinor,
    currency: "RUB",
    mode: "test",
    providerCreatedAt: at,
    providerCapturedAt: status === "succeeded" ? at : null,
    paymentMethodType: null,
    identity: {
      purpose: "main_residency",
      operationId: f.descriptor.legacyDeliveryOperationId,
      orderId: f.order.orderId,
      userId: f.userId,
    },
    evidenceDigest: hash(randomUUID()),
    observedAt: at,
  };
  expect(
    await call("public_payment_bind", [
      f.descriptor.requestId,
      providerId,
      JSON.stringify({
        version: 1,
        complete: true,
        exactCandidates: 1,
        observation: fact,
      }),
    ]),
  ).toMatchObject({ state: "bound" });
  const observationId = (await call("public_payment_observe", [
    f.descriptor.requestId,
    providerId,
    JSON.stringify(fact),
  ])) as string;
  const action = await call("public_payment_resolve", [
    f.descriptor.requestId,
    observationId,
  ]);
  return { ...f, fact, observationId, action, providerId };
}
type Bound = Awaited<ReturnType<typeof bind>>;
// This witness exercises SQL's trusted financial boundary. Task4 supplies the actual shared TS poster.
async function canonicalFacts(
  c: PoolClient,
  f: Bound,
  startsAt: string,
  endsAt: string,
) {
  await c.query(
    "update expert_residency_payment_attempts set status='settled',resolved_at=early_bird_current_time() where id=(select payment_attempt_id from expert_residency_provider_operations where id=$1)",
    [f.descriptor.legacyDeliveryOperationId],
  );
  await c.query(
    `insert into expert_residency_provider_event_inbox(provider,external_event_id,payload_digest,event_kind,identity_version,payment_id,order_id,amount_minor,currency,occurred_at,authenticated,verification_id,verifier_key_version,verified_at,status,processed_at,result_code)
 values('yookassa',$1,$2,'settled',1,$3,$4,$5,'RUB',$6,true,$7,'public-v1',$6,'processed',early_bird_current_time(),'settled')`,
    [
      `public:${f.descriptor.requestId}:${f.observationId}`,
      f.fact.evidenceDigest.slice(7),
      f.providerId,
      f.order.orderId,
      f.order.cashMinor,
      at,
      `public:${f.observationId}`,
    ],
  );
  await c.query(
    "update expert_residency_orders set status='settled',provider_payment_id=$2,settled_at=early_bird_current_time(),residency_starts_at=$3,residency_ends_at=$4 where id=$1",
    [f.order.orderId, f.providerId, startsAt, endsAt],
  );
}
async function apply(f: Bound) {
  const c = await db.db.$client.connect();
  try {
    await c.query("begin");
    await lock(c, f);
    const action = await call(
      "public_payment_apply_guard",
      [f.descriptor.requestId, f.observationId, f.action.applyAttemptId],
      c,
    );
    expect(action.evidence.expectedPeriod).toEqual(
      expect.objectContaining({
        startsAt: expect.any(String),
        endsAt: expect.any(String),
      }),
    );
    await canonicalFacts(
      c,
      f,
      action.evidence.expectedPeriod.startsAt,
      action.evidence.expectedPeriod.endsAt,
    );
    await c.query("commit");
    return action;
  } catch (e) {
    await c.query("rollback");
    throw e;
  } finally {
    c.release();
  }
}
it("rolls back never-admitted abandonment with canonical expiry and releases genuine reserved credit exactly once after commit", async () => {
  const f = await owner();
  await earnCredit(f);
  const checkoutState = await checkout(f);
  expect(await state(checkoutState)).toMatchObject({
    state: "prepared",
    status: "payment_pending",
    reserved: "-100000",
    releases: 0,
    observations: 0,
  });
  await clock(true);
  await expect(canonicalExpire(checkoutState, true)).rejects.toThrow(
    "fixture_abort_after_canonical_expiry",
  );
  expect(await state(checkoutState)).toMatchObject({
    state: "prepared",
    status: "payment_pending",
    reserved: "-100000",
    releases: 0,
    observations: 0,
  });
  expect(await canonicalExpire(checkoutState)).toBe(true);
  expect(await state(checkoutState)).toMatchObject({
    state: "abandoned",
    status: "expired",
    reserved: "0",
    releases: 1,
    observations: 0,
  });
  expect(await canonicalExpire(checkoutState)).toBe(false);
  await clock();
  expect(await admit(checkoutState)).toBeNull();
  expect(await claim(checkoutState)).toBeNull();
});
it.each(["admitted", "uncertain", "bound"] as const)(
  "never uses the no-send expiry path for %s delivery",
  async (phase) => {
    const f = await checkout(await owner());
    await admit(f);
    if (phase !== "admitted") await claim(f);
    if (phase === "bound") await bind(f, "pending");
    await clock(true);
    await expect(canonicalExpire(f)).rejects.toThrow();
    expect(await state(f)).toMatchObject({
      state: phase,
      status: "payment_pending",
      releases: 0,
    });
  },
);
it("persists exact capture-origin period, rejects an arbitrary later start, and preserves committed dates when later coverage queues before completion", async () => {
  const subject = await owner(),
    first = await checkout(subject);
  await admit(first);
  await claim(first);
  const paid = await bind(first);
  const c = await db.db.$client.connect();
  try {
    await c.query("begin");
    await lock(c, paid);
    const action = await call(
      "public_payment_apply_guard",
      [
        paid.descriptor.requestId,
        paid.observationId,
        paid.action.applyAttemptId,
      ],
      c,
    );
    expect(action.evidence.expectedPeriod).toEqual({
      startsAt: "2027-01-11T12:00:00.000Z",
      endsAt: "2027-02-10T12:00:00.000Z",
    });
    await c.query("savepoint bad_period");
    await expect(
      c.query(
        "update expert_residency_orders set status='settled',provider_payment_id=$2,settled_at=early_bird_current_time(),residency_starts_at='2027-01-12T12:00:00Z',residency_ends_at='2027-02-11T12:00:00Z' where id=$1",
        [paid.order.orderId, paid.providerId],
      ),
    ).rejects.toThrow(/public_financial_apply_context_required/u);
    await c.query("rollback to savepoint bad_period");
    await canonicalFacts(
      c,
      paid,
      action.evidence.expectedPeriod.startsAt,
      action.evidence.expectedPeriod.endsAt,
    );
    await c.query("commit");
  } catch (e) {
    await c.query("rollback");
    throw e;
  } finally {
    c.release();
  }
  const second = await checkout(subject);
  await admit(second);
  await claim(second);
  const next = await bind(second);
  const nextAction = await apply(next);
  expect(nextAction.evidence.expectedPeriod).toEqual({
    startsAt: "2027-02-10T12:00:00.000Z",
    endsAt: "2027-03-12T12:00:00.000Z",
  });
  expect(
    await call("public_payment_complete", [
      paid.descriptor.requestId,
      paid.action.applyAttemptId,
    ]),
  ).toMatchObject({
    kind: "already_applied",
    evidence: {
      expectedPeriod: {
        startsAt: "2027-01-11T12:00:00.000Z",
        endsAt: "2027-02-10T12:00:00.000Z",
      },
    },
  });
  await expect(
    db.db.$client.query(
      "update public_expert_payment_requests set apply_expected_start=apply_expected_start+interval '1 day' where id=$1",
      [paid.descriptor.requestId],
    ),
  ).rejects.toThrow(/public_request_immutable/u);
});

it("refuses legacy order-first expiry without waiting for a competing subject owner, then permits a clean retry", async () => {
  const f = await checkout(await owner());
  await clock(true);
  const orderOwner = await db.db.$client.connect();
  const subjectOwner = await db.db.$client.connect();
  const before = await state(f);
  try {
    await orderOwner.query("begin");
    await orderOwner.query(
      "select id from expert_residency_orders where id=$1 for update",
      [f.order.orderId],
    );
    await subjectOwner.query("begin");
    await subjectOwner.query(
      "select pg_advisory_xact_lock(hashtextextended($1,0))",
      [f.userId],
    );
    await orderOwner.query("set local statement_timeout='1500ms'");
    // The error must be the financial guard, not timeout/deadlock cancellation.
    await expect(
      orderOwner.query(
        "update expert_residency_orders set status='expired',updated_at=early_bird_current_time() where id=$1",
        [f.order.orderId],
      ),
    ).rejects.toThrow("public_financial_apply_context_required");
    await orderOwner.query("rollback");
    expect(await state(f)).toEqual(before);
    await subjectOwner.query("rollback");
    expect(await canonicalExpire(f)).toBe(true);
    expect(await state(f)).toMatchObject({
      state: "abandoned",
      status: "expired",
      observations: 0,
    });
  } finally {
    await orderOwner.query("rollback");
    await subjectOwner.query("rollback");
    orderOwner.release();
    subjectOwner.release();
  }
});
